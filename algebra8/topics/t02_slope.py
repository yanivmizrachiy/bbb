    W.Q(3, "נתון ישר העובר דרך הנקודות " + L("(3,0)") + " ו־" + L("(2,5)") + ". האם הישר מייצג פונקציה עולה, יורדת או קבועה? נמקו." + lines(1))

    W.Q(4, "השלימו את הטבלה כך שתתאים לשיעורי נקודות על אותו קו ישר, ומצאו את שיפוע הישר:"
        + table([L("x"), "−2", "−1", "0", "1", "2"], [[L("y"), "", "6", "", "", "10"]])
        + parts([("א.", "השלימו את התאים החסרים.", 0), ("ב.", "מהו השיפוע של הישר המתאים לטבלה?", 1)]))

