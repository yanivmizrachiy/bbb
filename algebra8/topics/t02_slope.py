    W.Q(10, "יובל סרטטה גרף של ישר עולה העובר בנקודה " + L("(2,3)") + " ובנקודה נוספת מבין אלה. סמנו את הנקודה הנוספת: "
        + L("(1,3)") + " · " + L("(4,2)") + " · " + L("(3,7)") + " · " + L("(0,5)") + "." + lines(1))

