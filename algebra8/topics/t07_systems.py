# -*- coding: utf-8 -*-
"""נושא 7 — פתרון מערכות משוואות לינאריות בשני נעלמים."""
import wsengine as W
from wsengine import L, parts, table, img, lines


def build():
    W.SECTION("מערכות משוואות לינאריות", "אלגברה · כיתה ח' · פתרון גרפי ואלגברי בשני נעלמים", "#d97706")

    W.Q(1, "נתונות שתי הפונקציות " + L("f(x) = 2x − 2") + " ו־" + L("g(x) = −x + 4") + "."
        + parts([("א.", "הציבו את ערכי " + L("x") + " מ־" + L("−2") + " עד " + L("3") + " בשתי המשוואות ורשמו בטבלה את ערכי " + L("y") + ".", 0),
                 ("ב.", "עבור איזה ערך של " + L("x") + " מתקיים " + L("f(x) = g(x)") + "?", 1),
                 ("ג.", "עבור אילו ערכים של " + L("x") + " מתקיים " + L("f(x) > g(x)") + "?", 1)]))

    W.Q(2, "נתונות שתי הפונקציות " + L("f(x) = 3x + 5") + " ו־" + L("g(x) = −2x − 10") + "."
        + parts([("א.", "סרטטו את הגרפים שלהן במערכת צירים משותפת.", 0),
                 ("ב.", "מהם שיעורי נקודת החיתוך של שני הישרים?" + W.opair(), 0),
                 ("ג.", "מצאו את ערך " + L("x") + " בנקודת החיתוך באמצעות השוואת הביטויים האלגבריים ופתרון המשוואה.", 2)]))

    W.Q(3, "לפניכם גרפים של שני ישרים " + L("f(x)") + ", " + L("g(x)") + " הנחתכים בנקודה " + L("A(5,2)") + ". סמנו ליד כל טענה האם היא נכונה או לא נכונה."
        + img("p91", 66) + lines(2))

    W.Q(4, "נתונים שני ישרים: ישר א' עובר דרך הנקודה " + L("(1,1)") + " ושיפועו " + L("2") + "; ישר ב' הוא ישר אופקי העובר בנקודה " + L("(1,4)") + "."
        + parts([("א.", "מצאו את המשוואות של שני הישרים.", 1),
                 ("ב.", "מצאו את נקודת החיתוך באמצעות השוואת הביטויים (שימו לב שיש לה שני שיעורים)." + W.opair(), 0),
                 ("ג.", "סרטטו את הישרים וּודאו שהם נחתכים בנקודה שמצאתם.", 0)]))

    W.Q(5, "נתונות שתי המשוואות " + L("f(x) = −2x + 3") + " ו־" + L("g(x) = 3x − 7") + "."
        + parts([("א.", "שרטטו את הישרים על אותה מערכת צירים.", 0),
                 ("ב.", "מהו תחום הערכים של " + L("x") + " שעבורו " + L("f(x) < 0") + "?", 1),
                 ("ג.", "מהם שיעורי הנקודה שבה " + L("f(x) = g(x)") + "?" + W.opair(), 0),
                 ("ד.", "מהו תחום הערכים של " + L("x") + " שעבורו " + L("f(x) < g(x)") + "?", 1)]))

    W.Q(6, "נתונים שני ישרים במערכת צירים:"
        + img("p93", 64)
        + parts([("א.", "מצאו את שיעורי נקודת החיתוך בין שני הישרים." + W.opair(), 0),
                 ("ב.", "מבין שלושת זוגות המשוואות, איזה זוג מתאר את הישרים הנתונים? נמקו.", 1)]))

    W.Q(7, "פתרו את מערכת המשוואות הבאה ומצאו את נקודת החיתוך, באמצעות השוואת הביטויים: " + L("y = 3x − 5") + " ו־" + L("y = 2x") + "." + lines(2) + W.opair())

    W.Q(8, "במפעל משדרים משני סוגים: \"קל\" ו\"לוויני\". סמנו ב־" + L("x") + " את מספר המשדרים מהסוג ה\"קל\" וב־" + L("y") + " את מספר המשדרים ה\"לוויניים\". כתבו מערכת של שתי משוואות המייצגת את הנתונים, ופתרו אותה."
        + img("p99", 70) + lines(3))

    W.ENDSEC()
