from wsengine import L, parts, mc, img, lines, fig


def _opairs(labels):
    """A wrapping row of labelled ordered-pair answer fields: A ( , )  B ( , ) ..."""
    cells = "".join(
        f'<div style="display:inline-flex;align-items:center;gap:7px"><b>{L(p)}</b>{W.opair()}</div>'
        for p in labels)
    return f'<div style="display:flex;flex-wrap:wrap;gap:0 24px;align-items:center">{cells}</div>'


