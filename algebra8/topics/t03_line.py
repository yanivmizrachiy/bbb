# -*- coding: utf-8 -*-
"""נושא 3 — ייצוג אלגברי של פונקציה ליניארית (משוואת הישר)."""
import wsengine as W
import charts as C
from wsengine import L, parts, mc, table, img, lines, fig


def build():
    W.SECTION("ייצוג אלגברי של פונקציה ליניארית", "אלגברה · כיתה ח' · משוואת הישר y = mx + b והתאמת ישר למשוואתו", "#4f46e5")

    W.Q(1, "לפניכם טבלת ערכים של פונקציה:"
        + table([L("x"), "1", "2", "3", "4", "5", "6", "7"], [[L("y"), "4", "7", "10", "13", "16", "19", "22"]])
        + parts([("א.", "סרטטו את הנקודות ובדקו האם ניתן להעביר דרכן ישר."
                  + fig(C.coord(0, 8, 0, 24, xlabel="x", ylabel="y", xstep=1, ystep=4, labx=1, laby=4, W=360, H=215), w=58), 0),
                 ("ב.", "האם הטבלה מתארת קצב שינוי קבוע של הפונקציה? נמקו.", 1),
                 ("ג.", "מהו קצב השינוי?", 1),
                 ("ד.", "מהם ערכי ה־" + L("y") + " של הנקודות על הישר כאשר " + L("x = 12") + " או " + L("x = −2") + "?", 1)]))

    W.Q(2, "נתונה המשוואה " + L("y = 2x − 4") + "."
        + parts([("א.", "בנו טבלת ערכים חלקית ובה " + L("5") + " נקודות — בחרו ערכי " + L("x") + " וחשבו " + L("y") + ":"
                  + W.filltable(L("x"), L("y"), given=["−1", "0", "1", "2", "3"]), 0),
                 ("ב.", "סרטטו את הגרף של הישר המתאים."
                  + fig(C.coord(-2, 4, -8, 6, xlabel="x", ylabel="y", xstep=1, ystep=2, labx=1, laby=2, W=360, H=210), w=56), 0),
                 ("ג.", "מהו קצב השינוי (השיפוע) של הישר?", 1),
                 ("ד.", "מהו ערך ה־" + L("y") + " כאשר " + L("x = 0") + "?", 1),
                 ("ה.", "עבור איזה ערך של " + L("x") + " ערך ה־" + L("y") + " הוא אפס?", 1)]))

    W.Q(3, "נתונה משוואת הישר " + L("y = 4x − 10") + "."
        + parts([("א.", "מבין הנקודות " + L("(15,50)") + " ו־" + L("(11,35)") + ", סמנו את הנקודה הנמצאת על גרף הישר ונמקו.", 1),
                 ("ב.", "רשמו שיעורי נקודה נוספת הנמצאת על גרף הישר." + W.opair(), 0)]))

    W.Q(4, "נתונה משוואת הישר " + L("y − 3x = −9") + "."
        + parts([("א.", "על גרף הישר נקודה ששיעור ה־" + L("x") + " שלה הוא " + L("4") + ". חשבו את שיעור ה־" + L("y") + ".", 1),
                 ("ב.", "האם הנקודה " + L("(4,4)") + " נמצאת על גרף הפונקציה? הסבירו.", 1)]))

    W.Q(5, "נתונה משוואת הישר " + L("y = 1 − 3x") + "."
        + parts([("א.", "השלימו את שיעורי הנקודות הנמצאות על הישר: " + L("(5, ?)") + ", " + L("(?, −5)") + ", " + L("(0, ?)") + ".", 1),
                 ("ב.", "רשמו שיעורי נקודה שאינה נמצאת על הישר." + W.opair(), 0)]))

    W.Q(6, "שלוש הנקודות " + L("(−4,1)") + ", " + L("(2,−5)") + ", " + L("(0,−3)") + " נמצאות על ישר אחד. סמנו את משוואת הישר:"
        + mc([("", L("y = 2x − 9")), ("", L("y = −3 + x")), ("", L("y = −x − 3")), ("", L("y = −2x − 7"))]))

    W.Q(7, "נתונה משוואת הישר " + L("y = 2x − 4") + "."
        + parts([("א.", "מהו ערך ה־" + L("y") + " כאשר " + L("x = 0") + "?", 1),
                 ("ב.", "מהו ערך ה־" + L("x") + " כאשר " + L("y = 0") + "?", 1),
                 ("ג.", "סמנו על מערכת צירים את שתי נקודות החיתוך של הישר עם הצירים.", 0),
                 ("ד.", "סרטטו את הישר המתאים.", 0)]))

    W.Q(8, "נתונות " + L("4") + " משוואות ישרים: " + L("y = 4x") + " · " + L("y = −4") + " · " + L("y = x − 4") + " · " + L("y = −4x + 1") + ". רשמו לצד כל תכונה את המשוואה המתאימה:"
        + parts([("א.", "ישר עולה החותך את ציר " + L("y") + " בחלקו השלילי.", 1),
                 ("ב.", "ישר העובר בראשית הצירים.", 1),
                 ("ג.", "שיפוע הישר הוא " + L("0") + ".", 1),
                 ("ד.", "ישר יורד.", 1)]))

    W.Q(9, "לפניכם ארבעה גרפים של פונקציות ליניאריות וארבע משוואות. התאימו לכל משוואה את הגרף המתאים: "
        + L("y = 3x + 4") + " · " + L("y = −3x − 4") + " · " + L("y = 3x − 4") + " · " + L("y = −3x + 4") + "."
        + fig(C.grid_of([
            C.coord(-3, 3, -9, 9, lines=[(3, 4, "#1f2a44")], title="I", ystep=3, labx=1, laby=3, W=300, H=265),
            C.coord(-3, 3, -9, 9, lines=[(-3, 4, "#1f2a44")], title="II", ystep=3, labx=1, laby=3, W=300, H=265),
            C.coord(-3, 3, -9, 9, lines=[(3, -4, "#1f2a44")], title="III", ystep=3, labx=1, laby=3, W=300, H=265),
            C.coord(-3, 3, -9, 9, lines=[(-3, -4, "#1f2a44")], title="IV", ystep=3, labx=1, laby=3, W=300, H=265),
          ], 2, 300, 265), w=80) + lines(1))

    W.Q(10, "נתונה משוואת הישר " + L("y = −2x + 6") + "."
        + parts([("א.", "מהי נקודת החיתוך של הישר עם הציר האנכי?" + W.opair(), 0),
                 ("ב.", "האם הישר עולה או יורד? מהו השיפוע?", 1),
                 ("ג.", "סמנו על סמך נקודת החיתוך והשיפוע שתי נקודות נוספות על הישר (מימין ומשמאל לציר האנכי).", 0),
                 ("ד.", "סרטטו את הישר. מהי נקודת החיתוך שלו עם הציר האופקי?" + W.opair(), 0)]))

    W.Q(11, "נתונה המשוואה " + L("y = −0.5x − 2") + "."
        + fig(C.coord(-8, 6, -6, 4, lines=[(-0.5, -2, "#4f46e5")], xlabel="x", ylabel="y", labx=2, laby=2), w=54)
        + parts([("א.", "סרטטו את הישר.", 0),
                 ("ב.", "מהן נקודות החיתוך של הישר עם הצירים?" + W.opair() + W.opair(), 0),
                 ("ג.", "מצאו את היחס בין ההפרש בשיעורי ה־" + L("y") + " לבין ההפרש בשיעורי ה־" + L("x") + " של נקודות החיתוך. מה הקשר למשוואת הישר?", 2)]))

    W.Q(12, "במערכת הצירים מסורטטים המשולשים " + L("ADC") + " ו־" + L("ABC") + ". נתונה משוואת הישר " + L("y = 0.25x + 2") + "."
        + img("p58", 64)
        + parts([("א.", "איזו צלע נמצאת על גרף הישר שמשוואתו נתונה?", 1),
                 ("ב.", "מה משוואת הישר שעליו נמצאת הצלע " + L("AC") + "?", 1)]))

    W.Q(13, "לפניכם ארבע משוואות: " + L("y = −2x + 4") + " · " + L("y + 2x = −5") + " · " + L("y = 2x + 3") + " · " + L("y = −6 − 2x") + ". שלושה מהישרים מקבילים."
        + parts([("א.", "סמנו את המשוואה שהישר שלה אינו מקביל לשלושת האחרים.", 1),
                 ("ב.", "השלימו מספרים אפשריים למשוואה " + L("y = ___x + ___") + " כך שתהיה מקבילה למשוואה שסימנתם.", 1)]))

    W.Q(14, "לפניכם שני קטעים המסורטטים על מערכת צירים, היוצרים עם הצירים שני משולשים ישרי־זווית. אורכי הניצבים יוצרים את הפרופורציה " + L("OB/OC = OA/OD") + "."
        + img("p60", 64)
        + parts([("א.", "מצאו את שיעורי הנקודה " + L("B") + "." + W.opair(), 0),
                 ("ב.", "קבעו לכל קטע (" + L("AB") + ", " + L("CD") + ") האם הישר עולה או יורד.", 1),
                 ("ג.", "קבעו (ללא חישוב) לאיזה ישר שיפוע גדול יותר, ובדקו בעזרת חישוב.", 2)]))

    W.ENDSEC()
