    W.Q(12, "במערכת הצירים מסורטטים המשולשים " + L("ADC") + " ו־" + L("ABC") + ". נתונה משוואת הישר " + L("y = 0.25x + 2") + "."
        + img("p58", 64)
        + parts([("א.", "איזו צלע נמצאת על גרף הישר שמשוואתו נתונה? " + W.blank(80), 0),
                 ("ב.", "מה משוואת הישר שעליו נמצאת הצלע " + L("AC") + "?" + W.ansval(L("y ="), w=110), 0)]))

    W.Q(13, "לפניכם ארבע משוואות. שלושה מהישרים מקבילים."
        + parts([("א.", "סמנו את המשוואה שהישר שלה אינו מקביל לשלושת האחרים."
                  + mc([("", L("y = −2x + 4")), ("", L("y + 2x = −5")), ("", L("y = 2x + 3")), ("", L("y = −6 − 2x"))]), 0),
                 ("ב.", "השלימו מספרים אפשריים למשוואה " + '<span dir="ltr">y = ' + W.blank(40) + 'x + ' + W.blank(40) + '</span>' + " כך שתהיה מקבילה למשוואה שסימנתם.", 0)]))

    W.Q(14, "לפניכם שני קטעים המסורטטים על מערכת צירים, היוצרים עם הצירים שני משולשים ישרי־זווית. אורכי הניצבים יוצרים את הפרופורציה " + L("OB/OC = OA/OD") + "."
        + img("p60", 64)
        + parts([("א.", "מצאו את שיעורי הנקודה " + L("B") + "." + W.opair(), 0),
                 ("ב.", "קבעו לכל קטע (" + L("AB") + ", " + L("CD") + ") האם הישר עולה או יורד."
                  + W.tagblanks([L("AB"), L("CD")], w=64), 0),
                 ("ג.", "קבעו (ללא חישוב) לאיזה ישר שיפוע גדול יותר, ובדקו בעזרת חישוב."
                  + W.ansval("שיפוע גדול יותר לישר:", w=56), 2)]))

    W.ENDSEC()
