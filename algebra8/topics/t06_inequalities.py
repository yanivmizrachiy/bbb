# -*- coding: utf-8 -*-
"""נושא 6 — אי-שוויונות ממעלה ראשונה ופתרונן."""
import wsengine as W
import charts as C
from wsengine import L, parts, mc, img, lines, fig


def build():
    W.SECTION("אי-שוויונות ממעלה ראשונה", "אלגברה · כיתה ח' · הרכבה, פתרון ותחום פתרון משותף", "#e11d48")

    W.Q(1, "אריאל צריך לבנות טיסנים רבים ככל האפשר ב־" + L("50") + " דקות. דרושות לו " + L("5") + " דקות לטיסן מדגם " + L("A") + " ו־" + L("3") + " דקות לטיסן מדגם " + L("B") + "."
        + parts([("א.", "אריאל רוצה לבנות " + L("5") + " טיסנים מדגם " + L("A") + " ו־" + L("10") + " מדגם " + L("B") + ". הסבירו מדוע לא יספיק לו הזמן.", 1),
                 ("ב.", L("a") + " מספר הטיסנים מדגם " + L("A") + " ו־" + L("b") + " מדגם " + L("B") + ". באיזה אי־שוויון יוכל אריאל לבדוק אם יש מספיק זמן?"
                  + mc([("א.", L("a + b ≤ 50")), ("ב.", L("a + b + 8 ≤ 50")), ("ג.", L("3a + 5b ≤ 50")), ("ד.", L("5a + 3b ≤ 50"))]), 0)]))

    W.Q(2, "לדנה שלושה מטילים מתכתיים זהים. הסרטוטים מתארים שני מצבי מאזניים: מטיל אחד מול משקולות " + L("8") + " גרם, ושלושה מטילים מול משקולות " + L("20") + " גרם. מה יכול להיות משקל מטיל אחד?"
        + fig(C.balance_scale(), w=52)
        + mc([("א.", "5 ג'"), ("ב.", "6 ג'"), ("ג.", "7 ג'"), ("ד.", "8 ג'")]))

    W.Q(3, "לפניכם אי־שוויון: " + L("4x + 30 < 9x") + ". האם " + L("−8") + " הוא אחד הפתרונות? נמקו." + lines(1))

    W.Q(4, "נתון אי־שוויון: " + L("−4x < 12") + "."
        + parts([("א.", "הסבירו, מבלי לפתור, מדוע כל מספר חיובי פותר אותו.", 1),
                 ("ב.", "תנו דוגמה למספר שלילי שהוא פתרון של האי־שוויון.", 1)]))

    W.Q(5, "לפניכם אי־שוויון: " + L("3x > −4") + "."
        + parts([("א.", "הביאו דוגמה למספר שהוא פתרון.", 1),
                 ("ב.", "הביאו דוגמה למספר שאינו פתרון.", 1)]))

    W.Q(6, "מהם תחומי הערכים של " + L("x") + " שעבורם מתקיימים אי־השוויונות הבאים?"
        + parts([("א.", L("x + 3 < 7.1"), 1), ("ב.", L("8x − 4 > 17.2"), 1),
                 ("ג.", L("4x − 3 > 2x + 5"), 1), ("ד.", L("2(x + 5) > x + 18"), 1)]))

    W.Q(7, "נתון הישר שמשוואתו " + L("y = 2x − 3") + ". מי מהנקודות מונחת מעל הישר, מי מתחתיו ומי עליו? "
        + L("(−2,−7)") + " · " + L("(−1,−4)") + " · " + L("(1,−2)") + " · " + L("(2,2)") + " · " + L("(3,3)") + "." + lines(2))

    W.Q(8, "פתרו את אי־השוויונות הבאים:"
        + parts([("א.", L("−3(x + 1) < 6x"), 1), ("ב.", L("(5x − 2)/2 ≤ 8"), 1)]))

    W.Q(9, "נתונים שני אי־שוויונות:"
        + parts([("א.", "פתרו את הראשון: " + L("3x > x − 4") + ".", 1),
                 ("ב.", "פתרו את השני: " + L("2x + 1 < 12 − 2x") + ".", 1),
                 ("ג.", "מהו תחום הערכים של " + L("x") + " שעבורו מתקיימים שני האי־שוויונות (תחום פתרון משותף)?", 1)]))

    W.Q("המעבר לאנרגיה סולארית", "<b>שאלת סיכום אוריינית.</b> שתי תכניות לתשלום חשמל: <b>\"חשמל רגיל\"</b> — " + L("0.6") + " ש\"ח לכל קוט\"ש, ללא תשלום קבוע; <b>\"גג ירוק\"</b> — אחזקה קבועה " + L("120") + " ש\"ח לחודש, ו־" + L("0.2") + " ש\"ח לכל קוט\"ש. נסמן ב־" + L("x") + " את מספר הקוט\"ש בחודש."
        + parts([("א.", "כתבו ביטוי למחיר החודשי בכל תכנית.", 2),
                 ("ב.", "אם צרכו " + L("200") + " קוט\"ש — מה ההפרש בין התכניות?"
                  + mc([("א.", "\"חשמל רגיל\" זולה ב־40 ש\"ח"), ("ב.", "\"גג ירוק\" זולה ב־40 ש\"ח"), ("ג.", "המחיר זהה"), ("ד.", "\"גג ירוק\" יקרה ב־120 ש\"ח")]), 0),
                 ("ג.", "איזה אי־שוויון מייצג את המצב שבו \"גג ירוק\" זולה יותר? מהי צריכת החשמל שממנה משתלם לעבור?", 2),
                 ("ד.", "משפחה ממוצעת צורכת כ־" + L("800") + " קוט\"ש. האם הייתם ממליצים לעבור? נמקו בעזרת חישוב. כיצד תשפיע קפיצה של " + L("50%") + " בקיץ על החיסכון? (התייחסו לשיפוע)", 3)]), src="אוריינות")

    W.ENDSEC()
