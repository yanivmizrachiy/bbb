    W.SECTION("משוואות עם הגדלה/הקטנה באחוזים", "אלגברה · כיתה ח' · בעיות מילוליות רב־שלביות עם אחוזים", "#7c3aed")

    W.Q(1, "נתון ריבוע. אם נגדיל שתי צלעות נגדיות שלו ב־" + L("15%") + ", נקבל מלבן שהיקפו גדול ב־" + L("6") + " ס\"מ מהיקף הריבוע. מה אורך צלע הריבוע? מה שטח הריבוע? מה שטח המלבן המוגדל?" + lines(2)
        + W.ansval("צלע הריבוע:", "ס\"מ") + W.ansval("שטח הריבוע:", "סמ\"ר") + W.ansval("שטח המלבן:", "סמ\"ר"))

    W.Q(2, "היקף מלבן הוא " + L("100") + " ס\"מ. צלע אחת היא " + L("20%") + " מהיקפו. בכמה ס\"מ יש לקצר את הצלע כדי שאורכה יהיה " + L("10%") + " מההיקף המקוצר?" + lines(2)
        + W.ansval("יש לקצר ב:", "ס\"מ"))

    W.Q(3, "בשני אולמות קולנוע סך הכול " + L("240") + " צופים. אם " + L("20%") + " מהצופים באולם א' יעברו לאולם ב', יהיה מספר הצופים בשני האולמות שווה. כמה צופים בכל אולם?" + lines(1)
        + W.ansval("אולם א':", "צופים") + W.ansval("אולם ב':", "צופים"))

    W.Q(4, "מהכסף שהיה לי בארנק הוצאתי " + L("17%") + " על ספרים ו־" + L("18%") + " על ארוחה. על הארוחה הוצאתי " + L("5") + " שקלים יותר מאשר על הספרים. כמה כסף היה לי בארנק?" + lines(2)
        + W.ansval("", "₪"))

    W.Q(5, "אלון קנה חולצה ומכנסיים. מחיר החולצה נמוך ב־" + L("30%") + " ממחיר המכנסיים. " + L("x") + " מייצג את מחיר המכנסיים בש\"ח."
        + parts([("א.", "כתבו ביטוי אלגברי למחיר החולצה בש\"ח." + W.ansval("מחיר החולצה:", w=110), 0),
                 ("ב.", "אלון שילם " + L("204") + " ש\"ח על החולצה והמכנסיים יחד. מהו מחיר המכנסיים?"
                  + lines(1) + W.ansval("מחיר המכנסיים:", "ש\"ח"), 0)]))

    W.Q(6, "כרטיס לסרט בקולנוע אוריון עולה " + L("35") + " ₪."
        + parts([("א.", "מחיר הכרטיס עלה ל־" + L("37.80") + " ₪. פי כמה המחיר החדש מהקודם? בכמה אחוזים התייקר?"
                  + W.ansval("פי", w=56) + W.ansval("התייקר ב:", "%", w=56), 0),
                 ("ב.", "כעבור שנה הורידו את המחיר בחזרה ל־" + L("35") + " ₪. פי כמה המחיר האחרון מהמחיר לאחר ההעלאה? בכמה אחוזים הוזל?"
                  + W.ansval("פי", w=56) + W.ansval("הוזל ב:", "%", w=56), 0),
                 ("ג.", "בקולנוע אחר שיעור ההתייקרות זהה. כתבו ביטוי אלגברי למחיר לאחר ההתייקרות אם המחיר המקורי היה " + L("x") + "."
                  + W.ansval("המחיר לאחר ההתייקרות:", w=110), 0)]))

    W.Q(7, "<b>משימה מסכמת לדיון כיתתי.</b> דן קנה " + L("2") + " ק\"ג תפוחים ו־" + L("1.5") + " ק\"ג אגסים. מחיר ק\"ג תפוחים גדול ב־" + L("25%") + " ממחיר ק\"ג אגסים. בסך הכול שילם " + L("32") + " ₪."
        + "<p>הילה כתבה: " + L("x") + " = מחיר ק\"ג אגסים, " + L("1.25x") + " = מחיר ק\"ג תפוחים; המשוואה " + L("2·1.25x + 1.5x = 32") + ".</p>"
        + "<p>צופיה כתבה: " + L("x") + " = מחיר ק\"ג תפוחים, " + L("0.75x") + " = מחיר ק\"ג אגסים; המשוואה " + L("2x + 1.5·0.75x = 32") + ".</p>"
        + parts([("", "הסבירו את דרך הפתרון של כל אחת מהתלמידות. האם יקבלו פתרונות זהים? אם לא — מי צודקת? נמקו."
                  + mc([("", "כן — פתרונות זהים"), ("", "לא")]) + mc([("", "הילה צודקת"), ("", "צופיה צודקת")])
                  + W.justify("נמקו:", 2), 0)]))

    W.Q("העבודה היא חיינו", "משימה מסכמת אוריינית: התבוננו בנתונים ובגרפים, וענו על השאלות שבסעיפים." + img("p77", 80) + lines(3), src="אוריינות")
    W.Q("שיפור ציון", "משימה אוריינית: ענו על השאלות בעזרת הנתונים שלפניכם." + img("p80", 80) + lines(2), src="אוריינות")

    W.ENDSEC()
