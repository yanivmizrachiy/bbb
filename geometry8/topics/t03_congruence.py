# -*- coding: utf-8 -*-
"""נושא מרכזי: המעבר לחשיבה היסקית — חפיפת משולשים.
תתי-נושאים: השתלשלות היסקית וחפיפת צורות · משפטי החפיפה (צ.ז.צ · ז.צ.ז · צ.צ.צ) · שימושים בחפיפה."""
import wsengine as W
import geo
from wsengine import L, parts, mc, img, lines, fig


def build():
    # ===== השתלשלות היסקית — חפיפת צורות =====
    W.SECTION("השתלשלות היסקית — חפיפת צורות",
              "גאומטריה · כיתה ח' · מהי חפיפה, וזיהוי חלקים מתאימים בצורות חופפות", "#4f46e5")

    W.Q(1, "קבעו לכל טענה אם היא <b>נכונה</b> או <b>לא נכונה</b>, ונמקו (היעזרו בדוגמה נגדית כשצריך):"
        + parts([("א.", "שני מלבנים שהיקפם שווה — חופפים."
                  + mc([("", "נכונה"), ("", "לא נכונה")]), 1),
                 ("ב.", "שני מלבנים ששטחם שווה — חופפים."
                  + mc([("", "נכונה"), ("", "לא נכונה")]), 1),
                 ("ג.", "שני ריבועים שאורך צלעם " + L("5") + " ס\"מ — חופפים."
                  + mc([("", "נכונה"), ("", "לא נכונה")]), 1),
                 ("ד.", "שני משולשים שווי-צלעות שאורך צלעם " + L("5") + " ס\"מ — חופפים."
                  + mc([("", "נכונה"), ("", "לא נכונה")]), 1),
                 ("ה.", "שני מרובעים שאורך כל צלע בהם " + L("5") + " ס\"מ — חופפים בהכרח."
                  + mc([("", "נכונה"), ("", "לא נכונה")]), 1)]))

    W.Q(2, "נתונים שני המשולשים החופפים שלפניכם: " + L("△ABC ≅ △A'B'C'") + "."
        + fig(geo.cong_plain(), w=56)
        + parts([("א.", "רשמו את שלושת זוגות הצלעות המתאימות (השוות זו לזו).", 1),
                 ("ב.", "רשמו את שלושת זוגות הזוויות המתאימות.", 1),
                 ("ג.", "מדוע מול צלעות שוות מונחות זוויות שוות? הסבירו.", 1)]))

    # ===== חפיפת משולשים — שלושת משפטי החפיפה =====
    W.SECTION("חפיפת משולשים — משפטי החפיפה",
              "גאומטריה · כיתה ח' · צ.ז.צ (צלע-זווית-צלע) · ז.צ.ז (זווית-צלע-זווית) · צ.צ.צ (צלע-צלע-צלע)", "#0d9488")

    W.Q(1, "לכל זוג משולשים שלפניכם, הנתונים השווים מסומנים בסרטוט. קבעו לפי איזה <b>משפט חפיפה</b> אפשר לקבוע שהמשולשים חופפים, וכתבו את החפיפה בסימון " + L("△ABC ≅ △A'B'C'") + ":"
        + parts([("א.", "שתי צלעות והזווית הכלואה ביניהן." + fig(geo.cong_sas(), w=48)
                  + W.ansval("משפט החפיפה:", "", 90), 1),
                 ("ב.", "צלע ושתי הזוויות שעל קצותיה." + fig(geo.cong_asa(), w=48)
                  + W.ansval("משפט החפיפה:", "", 90), 1),
                 ("ג.", "שלוש הצלעות." + fig(geo.cong_sss(), w=48)
                  + W.ansval("משפט החפיפה:", "", 90), 1)]))

    W.Q(2, "המשולש " + L("ABC") + " הוא שווה-שוקיים (" + L("AB = AC") + "). הנקודה " + L("D") + " ממוקמת על המשך הצלע " + L("BC") + "."
        + fig(geo.isosceles_ext(), w=52)
        + parts([("א.", "כתבו את כל השוויונות המתקיימים בין צלעות וזוויות במשולשים " + L("ABD") + " ו־" + L("ACD") + ".", 2),
                 ("ב.", "המשולשים " + L("ABD") + " ו־" + L("ACD") + " <b>אינם</b> חופפים. האם יש בכך סתירה למשפט צ.ז.צ (שתי צלעות וזווית)?"
                  + mc([("", "כן"), ("", "לא")])
                  + W.justify("נמקו:", 2), 0)]))

    W.Q(3, "בשני משולשים נתון: " + L("AB = DE = 6") + " ס\"מ, " + L("BC = EF = 8") + " ס\"מ, " + L("∠B = ∠E = 50°") + "."
        + parts([("א.", "האם המשולשים חופפים? לפי איזה משפט?"
                  + mc([("", "כן"), ("", "לא")])
                  + W.ansval("לפי משפט:", "", 90), 0),
                 ("ב.", "מהו אורך הצלע " + L("DF") + " אם ידוע ש־" + L("AC = 9") + " ס\"מ?"
                  + W.ansval(L("DF") + " =", "ס\"מ")
                  + W.justify("נמקו:", 1), 0)]))

    # ===== שימושים בחפיפת משולשים =====
    W.SECTION("שימושים בחפיפת משולשים",
              "גאומטריה · כיתה ח' · הוכחת שוויון צלעות, זוויות ומקבילות בעזרת חפיפה", "#7c3aed")

    W.Q(1, "שני הקטעים " + L("AC") + " ו־" + L("BD") + " חוצים זה את זה בנקודה " + L("M") + " (כלומר " + L("AM = MC") + " ו־" + L("BM = MD") + ")."
        + fig(geo.x_segments(), w=50)
        + parts([("א.", "הוכיחו כי " + L("△ABM ≅ △CDM") + " (ציינו את המשפט והנימוקים).", 2),
                 ("ב.", "הסיקו מהחפיפה כי " + L("AB = CD") + ".", 1),
                 ("ג.", "הסבירו מדוע " + L("AB ∥ CD") + " (היעזרו בזוויות מתחלפות).", 1)]))

    W.Q(2, "<b>זוויות הבסיס במשולש שווה-שוקיים.</b> במשולש שווה-שוקיים " + L("AB = AC") + ", ו־" + L("AD") + " הוא חוצה זווית " + L("∠BAC") + " (" + L("D") + " על " + L("BC") + ")."
        + fig(geo.median_tri(), w=44)
        + parts([("א.", "הוכיחו כי " + L("△ABD ≅ △ACD") + ".", 2),
                 ("ב.", "הסיקו כי " + L("∠B = ∠C") + " (זוויות הבסיס שוות), וכי " + L("AD") + " הוא גם תיכון וגם גובה.", 2)]))

    W.Q(3, "במשולשים חופפים, התיכונים המתאימים שווים זה לזה. נתון " + L("△ABC ≅ △DEF") + ", " + L("AM") + " תיכון לצלע " + L("BC") + " ו־" + L("DN") + " תיכון לצלע " + L("EF") + ". הוכיחו כי " + L("AM = DN") + "." + lines(3))

    W.ENDSEC()
